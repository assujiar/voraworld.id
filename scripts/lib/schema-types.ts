import type { Sql } from 'postgres'

const camel = (s: string) => s.replace(/_([a-z])/g, (_, c: string) => c.toUpperCase())
const pascal = (s: string) => camel(s).replace(/^./, (c) => c.toUpperCase())

function tsType(dataType: string): string {
  if (['integer', 'smallint', 'bigint', 'numeric', 'real', 'double precision'].includes(dataType)) return 'number'
  if (dataType === 'boolean') return 'boolean'
  if (dataType.startsWith('timestamp') || dataType === 'date') return 'Date'
  if (dataType === 'json' || dataType === 'jsonb') return 'unknown'
  return 'string'
}

/** Renders `src/server/schema.ts` from the live (migrated) database. The migrations are the only source of truth. */
export async function renderSchemaTypes(sql: Sql): Promise<string> {
  const cols = await sql`
    select table_name, column_name, data_type, is_nullable
    from information_schema.columns
    where table_schema = 'public' and table_name <> 'schema_migrations'
    order by table_name, ordinal_position`
  const byTable = new Map<string, string[]>()
  for (const c of cols) {
    const line = `  ${camel(c.column_name as string)}: ${tsType(c.data_type as string)}${c.is_nullable === 'YES' ? ' | null' : ''}`
    byTable.set(c.table_name as string, [...(byTable.get(c.table_name as string) ?? []), line])
  }
  const parts = [
    '// GENERATED by `npm run gen:schema` from migrations/*.sql. Do not edit by hand.',
    '// Property names are camelCase (the database client maps them to snake_case columns).',
    '',
  ]
  for (const [table, lines] of byTable) parts.push(`export interface ${pascal(table)}Row {`, ...lines, '}', '')
  return parts.join('\n')
}
