/**
 * Rebuilds SUPABASE_MANUAL_SETUP.sql: every migration, in order, as ONE script for a brand-new Supabase project
 * (paste it into the SQL Editor). A test fails when the committed file is out of date.
 *
 *   npm run build:setup-sql           # rewrite the file
 *   npm run build:setup-sql -- --check   # exit 1 if it is out of date
 */
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { readMigrations } from './lib/migrations'

export const TARGET = join(process.cwd(), 'SUPABASE_MANUAL_SETUP.sql')

export function build(): string {
  const files = readMigrations()
  const last = files[files.length - 1].number
  const parts = [`-- ============================================================================
-- VORA: complete database setup for a COMPLETELY NEW Supabase project.
-- GENERATED by scripts/build-manual-setup.ts from migrations/0001..${last}. Do not edit by hand.
--
-- How to run: Supabase Dashboard -> SQL Editor -> New query -> paste this whole file -> Run.
-- Run it ONCE on an empty database. Afterwards run SUPABASE_VERIFICATION.sql.
-- Existing databases must use \`npm run db:migrate -- --apply\` instead (it applies only what is missing).
-- No demo users, customers or documents are created. Create the first admin with \`npm run users -- create EMAIL\`.
-- ============================================================================
`]
  for (const f of files) {
    parts.push(`\n-- ---------------------------------------------------------------------------\n-- ${f.name}\n-- ---------------------------------------------------------------------------\n`)
    parts.push(f.sql.replace(/\s+$/, '') + '\n')
  }
  parts.push(`
-- Record the applied migrations so \`npm run db:migrate\` recognises this database.
CREATE TABLE IF NOT EXISTS schema_migrations (name text PRIMARY KEY, sha256 text NOT NULL, applied_at timestamptz NOT NULL DEFAULT now());
ALTER TABLE schema_migrations ENABLE ROW LEVEL SECURITY;
`)
  const values = files.map((f) => `('${f.name}', '${createHash('sha256').update(readFileSync(join(process.cwd(), 'migrations', f.name))).digest('hex')}')`).join(',\n  ')
  parts.push(`INSERT INTO schema_migrations (name, sha256) VALUES\n  ${values}\nON CONFLICT (name) DO NOTHING;\n`)
  return parts.join('')
}

if (process.argv[1]?.endsWith('build-manual-setup.ts')) {
  const text = build()
  if (process.argv.includes('--check')) {
    if (!existsSync(TARGET) || readFileSync(TARGET, 'utf8') !== text) { console.error('SUPABASE_MANUAL_SETUP.sql is out of date: run `npm run build:setup-sql`'); process.exit(1) }
    console.log('SUPABASE_MANUAL_SETUP.sql is current')
  } else {
    writeFileSync(TARGET, text)
    console.log(`wrote SUPABASE_MANUAL_SETUP.sql (${text.split('\n').length - 1} lines)`)
  }
}
