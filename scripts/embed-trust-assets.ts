/**
 * Generates the two files the document-trust stamp is drawn from, so that the PDF painter, the browser preview and the watermark all use the same data:
 *
 *   src/content/stamp-art.ts          the path data of the APPROVED VORA SVGs (public/static/assets/vora-a-icon-primary.svg and vora-primary.svg), copied
 *                                     verbatim. Only the fill colour is chosen by the code that draws them; no coordinate is ever changed.
 *   src/content/helvetica-metrics.ts  glyph widths of the standard PDF fonts Helvetica and Helvetica-Bold, so that text is measured the same way in the
 *                                     browser as in the PDF.
 *
 *   npm run build:trust-assets        # regenerate after replacing the artwork
 *
 * A test fails if the generated files and their sources disagree.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { PDFDocument, StandardFonts } from 'pdf-lib'

const root = process.cwd()
export const ART_OUTPUT = join(root, 'src/content/stamp-art.ts')
export const METRICS_OUTPUT = join(root, 'src/content/helvetica-metrics.ts')
export const SOURCES = { icon: 'public/static/assets/vora-a-icon-primary.svg', wordmark: 'public/static/assets/vora-primary.svg' } as const

export interface ArtPath { d: string; evenOdd: boolean }
export interface Art { viewBox: [number, number, number, number]; paths: ArtPath[] }

/** Reads an approved SVG: its viewBox and the `d` of each path (and whether it is filled even-odd). Nothing else is taken from it. */
export function readArt(svg: string): Art {
  const vb = /viewBox="([^"]+)"/.exec(svg)?.[1].trim().split(/\s+/).map(Number)
  if (!vb || vb.length !== 4 || vb.some((n) => !Number.isFinite(n))) throw new Error('SVG without a viewBox')
  const paths = [...svg.matchAll(/<path\b([^>]*)>/g)].map((m) => ({ d: /\sd="([^"]+)"/.exec(m[1])![1], evenOdd: /fill-rule="evenodd"/.test(m[1]) }))
  if (!paths.length) throw new Error('SVG without paths')
  return { viewBox: vb as Art['viewBox'], paths }
}

export function buildArt(): string {
  const icon = readArt(readFileSync(join(root, SOURCES.icon), 'utf8'))
  const wordmark = readArt(readFileSync(join(root, SOURCES.wordmark), 'utf8'))
  return `// GENERATED by scripts/embed-trust-assets.ts from the approved SVGs. Do not edit by hand.\n`
    + `export interface ArtPath { d: string; evenOdd: boolean }\nexport interface Art { viewBox: [number, number, number, number]; paths: ArtPath[] }\n`
    + `/** ${SOURCES.icon} */\nexport const ICON_ART: Art = ${JSON.stringify(icon)}\n`
    + `/** ${SOURCES.wordmark} */\nexport const WORDMARK_ART: Art = ${JSON.stringify(wordmark)}\n`
}

export async function buildMetrics(): Promise<string> {
  const doc = await PDFDocument.create()
  const table: Record<string, Record<string, number>> = {}
  for (const [key, name] of [['regular', StandardFonts.Helvetica], ['bold', StandardFonts.HelveticaBold]] as const) {
    const font = await doc.embedFont(name)
    const widths: Record<string, number> = {}
    for (const code of font.getCharacterSet()) {
      if (code < 32 || code > 255 || (code > 126 && code < 160)) continue
      widths[String.fromCodePoint(code)] = Math.round(font.widthOfTextAtSize(String.fromCodePoint(code), 100000) / 100)   // 1/1000 em
    }
    table[key] = widths
  }
  return `// GENERATED by scripts/embed-trust-assets.ts from pdf-lib's standard font metrics. Do not edit by hand.\n/** Glyph widths in 1/1000 em, by character. */\nexport const HELVETICA_WIDTHS: Record<'regular' | 'bold', Record<string, number>> = ${JSON.stringify(table)}\n`
}

if (process.argv[1]?.endsWith('embed-trust-assets.ts')) {
  void buildMetrics().then((metrics) => {
    writeFileSync(ART_OUTPUT, buildArt())
    writeFileSync(METRICS_OUTPUT, metrics)
    console.log('Wrote', ART_OUTPUT, METRICS_OUTPUT)
  })
}
