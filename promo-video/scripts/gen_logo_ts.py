"""Write src/logo.ts with the path data of the approved VORA SVG (copied verbatim, never redrawn)."""
import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
svg = open(os.path.join(ROOT, "public", "img", "vora-primary.svg")).read()
ink, red = re.findall(r'<path[^>]*d="([^"]*)"', svg)
icon = open(os.path.join(ROOT, "public", "img", "vora-a-icon-primary.svg")).read()
out = f'''// Generated by scripts/gen_logo_ts.py from public/img/vora-primary.svg. Do not edit by hand.
export const LOGO_VIEWBOX = "132 164 1780 384";
export const LOGO_VB = {{ x: 132, y: 164, w: 1780, h: 384 }};
export const INK_PATH = "{ink}";
export const RED_PATH = "{red}";
'''
open(os.path.join(ROOT, "src", "logo.ts"), "w").write(out)
print("ok", len(ink), len(red))
